  function ensureLanguageSwitcher(root: HTMLElement): void {
    const cluster = root.querySelector<HTMLElement>('.status-cluster');
    if (!cluster || cluster.querySelector('[data-ui-language]')) return;
    const group = document.createElement('div');
    group.className = 'ui-language-switcher';
    group.setAttribute('role', 'group');
    group.setAttribute('aria-label', ui('表示言語', 'Bahasa tampilan'));
    group.dataset.noUiTranslation = 'true';
    group.innerHTML = `
      <button type="button" class="ui-language-button" data-ui-language="ja" lang="ja">日本語</button>
      <button type="button" class="ui-language-button" data-ui-language="id" lang="id">Indonesia</button>
    `;
    cluster.prepend(group);
  }

  export function applyDocumentUiLanguage(languageOverride?: UiLanguage): void {
    const language = languageOverride ?? currentUiLanguage();
    document.documentElement.lang = language;
    document.documentElement.dataset.uiLanguage = language;
    document.title = ui('畜産2号トレーナー', 'Pelatih Peternakan Tingkat 2', language);
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) {
      description.content = ui(
        '特定技能2号・畜産農業の非公式学習支援PWA。社内レビュー用Alphaです。',
        'PWA pembelajaran tidak resmi untuk ujian Keterampilan Spesifik Tingkat 2 bidang peternakan. Versi Alpha untuk tinjauan internal.',
        language,
      );
    }
  }

  export function applyUiLanguage(root: HTMLElement): void {
    ensureLanguageStyles();
    const mockActive = Boolean(root.querySelector('[data-mock-app-shell]'));
    if (!mockActive) ensureLanguageSwitcher(root);
    const language: UiLanguage = mockActive ? 'ja' : currentUiLanguage();
    applyDocumentUiLanguage(language);
    root.classList.toggle('ui-language-id', language === 'id');

    root.querySelectorAll<HTMLElement>('[data-ui-language]').forEach((button) => {
      const active = button.dataset.uiLanguage === language;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', String(active));
    });

    if (language !== 'id') return;

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const textNodes: Text[] = [];
    let current = walker.nextNode();
    while (current) {
      if (current instanceof Text) textNodes.push(current);
      current = walker.nextNode();
    }
    textNodes.forEach((node) => {
      const parent = node.parentElement;
      if (!parent || shouldProtectText(parent)) return;
      node.nodeValue = translateUiText(node.nodeValue ?? '', 'id');
    });

    root.querySelectorAll<HTMLElement>('[aria-label], [title], [placeholder]').forEach((element) => {
      if (element.closest('[data-no-ui-translation]') || element.closest(PROTECTED_CONTENT)) return;
      for (const attribute of ['aria-label', 'title', 'placeholder']) {
        const value = element.getAttribute(attribute);
        if (value) element.setAttribute(attribute, translateUiText(value, 'id'));
      }
    });
  }
