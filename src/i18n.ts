  export function translateUiText(value: string, language: UiLanguage = currentUiLanguage()): string {
    if (!value || !value.trim()) return value;
    if (language === 'ja') return value;
    const leading = value.match(/^\s*/)?.[0] ?? '';
    const trailing = value.match(/\s*$/)?.[0] ?? '';
    const core = normalizedText(value);
    const exact = UI_TEXT_ID[core]
      ?? CATEGORY_ID[core]
      ?? TOPIC_ID[core]
      ?? (REVIEW_MARK_ID as Record<string, string>)[core]
      ?? (QUESTION_STATUS_ID as Record<string, string>)[core];
    const translated = exact ?? translateDynamic(core) ?? phraseFallback(core);
    return `${leading}${translated}${trailing}`;
  }

  function shouldProtectText(parent: HTMLElement): boolean {
    if (parent.closest('[data-no-ui-translation]')) return true;
    if (parent.closest(PROTECTED_CONTENT)) return true;
    if (parent.matches('.answer-panel > p, .review-card > p, .review-source')) return true;
    return false;
  }

